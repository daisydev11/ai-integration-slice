import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

// Object storage, behind a two-method interface. The database only ever holds
// the key. In local development the "bucket" is a folder on disk (STORAGE_DIR,
// default ./storage, git-ignored). In production this file is the one place
// to swap in S3, R2 or GCS: put() and get() map directly to PutObject and GetObject.

function root(): string {
  return path.resolve(process.env.STORAGE_DIR || "storage");
}

function resolveKey(key: string): string {
  const full = path.resolve(root(), key);
  // Keys are generated by us, but never let one escape the storage root.
  if (!full.startsWith(root() + path.sep)) throw new Error("Invalid storage key.");
  return full;
}

export const storage = {
  async put(key: string, bytes: Uint8Array): Promise<void> {
    const file = resolveKey(key);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, bytes);
  },
  async get(key: string): Promise<Buffer> {
    return readFile(resolveKey(key));
  },
};
